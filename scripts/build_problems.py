"""Generate assets/js/problems.js from the ProofBench problem database.

Usage:
    python scripts/build_problems.py path/to/proofbench-statements/ProofBench/DATABASE/Database.json

Only test-taker fields are exported (id, name, difficulty, MSC, plain-language
summary, formal statement). Re-run whenever proofbench-statements changes.
"""

import json
import re
import sys
from pathlib import Path

AREAS = {
    "05C": "Graph theory",
    "05B": "Designs & matroids",
    "05D": "Extremal set theory",
}

OUT = Path(__file__).resolve().parent.parent / "assets" / "js" / "problems.js"


def category(difficulty: str) -> str:
    head = difficulty.split(" ")[0].lower()
    if head == "open":
        return "open"
    if head == "research":
        return "research"
    return "calibration"  # "Calibration ..." and "Undergraduate"


def note(difficulty: str) -> str:
    m = re.search(r"\((.*)\)\s*$", difficulty)
    return m.group(1) if m else ""


def resolved(difficulty: str) -> str:
    if "disproved in" in difficulty:
        return "disproved"
    if re.search(r"\bproved in OpenAI", difficulty):
        return "proved"
    return ""


def tex_dashes(text: str) -> str:
    return text.replace("--", "–")


def main(db_path: str) -> None:
    db = json.loads(Path(db_path).read_text(encoding="utf-8"))
    problems = []
    for p in db:
        msc_code = p["msc"][:5]
        problems.append({
            "id": p["id"],
            "name": tex_dashes(p["name"]),
            "cat": category(p["difficulty"]),
            "note": note(p["difficulty"]),
            "resolved": resolved(p["difficulty"]),
            "msc": p["msc"],
            "area": AREAS.get(msc_code[:3], "Other areas"),
            "summary": tex_dashes(p["informal_statement_summary"].strip()),
            "lean": p["formal_statement"][0].strip(),
        })
    body = json.dumps(problems, ensure_ascii=False, indent=0)
    OUT.write_text(
        "// Generated by scripts/build_problems.py from proofbench-statements. Do not edit by hand.\n"
        f"window.PB_PROBLEMS = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(problems)} problems to {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
